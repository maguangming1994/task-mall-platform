class ProductionLegalDocumentSeeder extends Seeder
{
    public function run(): void
    {
        foreach ($this->documents() as $document) {
            $exists = LegalDocumentVersion::query()
                ->where('document_type', $document['document_type'])
                ->where('version', $document['version'])
                ->exists();

            if ($exists) {
                $this->command?->info("跳过已存在协议：{$document['document_type']} {$document['version']}");

                continue;
            }

            LegalDocumentVersion::query()->create([
                'public_id' => (string) Str::ulid(),
                'document_type' => $document['document_type'],
                'version' => $document['version'],
                'title' => $document['title'],
                'content_format' => 'markdown',
                'content' => $document['content'],
                'content_hash' => hash('sha256', $document['content']),
                'consent_required' => $document['consent_required'],
                'withdrawal_allowed' => $document['withdrawal_allowed'],
                'status' => 'published',
                'effective_at' => Carbon::parse($document['effective_at']),
                'published_at' => now(),
                'change_summary' => $document['change_summary'],
            ]);

            $this->command?->info("已发布协议：{$document['document_type']} {$document['version']}");
        }
    }

