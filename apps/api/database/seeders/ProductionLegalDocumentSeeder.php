 * 用户协议 v3.2 / 隐私政策 v3.2 / 实名认证服务协议 v2.1 / 支付服务协议 v1.5。
 * 幂等：按 document_type + version 判重，已存在则跳过；无环境限制，由运维在生产显式执行。
