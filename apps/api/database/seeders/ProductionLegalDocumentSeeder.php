## 一、服务范围

1. 支付服务包括：商品订单的微信支付、钱包余额充值、任务报酬与活动奖励入账、闲置交易担保结算、退款原路退回或余额退回、实名认证后的余额提现。
2. 平台通过持有《支付业务许可证》的合作机构（当前为微信支付）完成资金通道服务；平台本身不从事吸收存款、资金拆借等金融业务。
3. 钱包余额、积分仅限在本平台内按规则使用与流通，不属于法定货币，不计付利息，不得用于平台外交易。

## 二、支付与订单

1. 你应在订单确认页面仔细核对商品、数量、金额与优惠信息，确认无误后完成支付。支付成功即表示你授权平台将相应资金按交易流程进行担保与结算。
2. 支付完成后，订单进入商家与平台的履约流程。发货、收货、确认收货时限以订单页面公示为准。
3. 发生退款时，原路支付的金额原则上退回原支付渠道，到账时间以支付机构处理为准（通常为 1 至 3 个工作日，特殊情况可能更长）；使用余额或积分支付的部分退回平台钱包或积分账户。

## 三、充值与提现

1. 充值金额仅可用于平台内消费，不支持无真实交易背景的提现或退回，法律另有规定或平台规则另有约定的除外。
2. 提现功能仅向完成实名认证的用户开放。你绑定的收款账户姓名应与实名认证姓名一致，平台有权对不一致的申请予以拒绝。
3. 为防范欺诈与洗钱风险，平台可对异常充值、异常交易、频繁退款后提现等行为进行风险核查，必要时要求你补充说明或凭证；核查期间相关资金可能被临时冻结。
4. 提现到账时间以支付机构与银行处理为准，单笔与单日限额以提现页面公示为标准。

## 四、任务报酬与闲置担保

1. 任务报酬在提交材料通过审核后发放至你的平台钱包；被驳回的提交不产生报酬，按任务规则退回修改。
2. 闲置交易资金在买家确认收货或系统超时自动确认后结算给卖家；发生售后仲裁的，以平台裁决结果为准进行资金分配。
3. 因买家或卖家不诚信导致的资金损失，由责任方承担；平台在能力范围内协助追偿，但不对第三方的偿付能力承担保证责任。

## 五、异常交易与风险处置

1. 你不得利用支付服务从事套现、洗钱、赌博、虚假交易、欺诈或其他违法活动，不得协助他人进行上述行为。
2. 发现可疑交易的，平台有权采取延迟结算、冻结余额、拒绝提现、限制功能等措施，并依法向监管机构报告及配合调查。
3. 因你主动泄露支付密码、验证码或账号被盗导致的损失，由你自行承担；发现异常应立即联系客服并报警。

## 六、争议处理

1. 支付状态以支付机构与平台系统记录为准。你对交易记录有异议的，可在交易发生后 30 日内提出，我们将协助核对。
2. 退款、退货、换货与运费承担争议，按照售后规则及双方举证处理；与支付机构之间的争议，可同时向支付机构客服反映。

## 七、协议变更与其他

1. 平台或支付机构可能根据法律法规、监管要求或通道规则调整服务内容与限额，调整将提前在页面公告。
2. 本协议未尽事宜，适用《校圈用户服务协议》《校圈隐私政策》及订单、钱包页面的具体规则。本协议与前述协议不一致的，就支付事项以本协议为准。
